import io.jsonwebtoken.Claims;
import io.jsonwebtoken.JwtException;
import lombok.RequiredArgsConstructor;
import org.springframework.security.authentication.BadCredentialsException;
import org.springframework.security.authentication.LockedException;
import org.springframework.security.core.AuthenticationException;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.time.temporal.ChronoUnit;

import org.modelmapper.ModelMapper;

@Service
@RequiredArgsConstructor
public class AuthService {
    private static final String DUMMY_HASH =
            "$2a$12$abcdefghijklmnopqrstuuJ1VQ0qQnXo4w5m9V5k0n3rYbq3S6yJi";

    private final UserRepository userRepository;
    private final TenantRepository tenantRepository;
    private final PasswordEncoder passwordEncoder;
    private final JwtService jwtService;
    private final RefreshTokenService refreshTokenService;
    private final MfaService mfaService;
    private final AuditService auditService;
    private final CustomUserDetailsService customUserDetailsService;
    private final SecurityProperties securityProperties;
    private final ModelMapper modelMapper;

    /* no rollback: the failed-attempt counter must be saved even though we throw */
    @Transactional(noRollbackFor = AuthenticationException.class)
    public AuthResponse login(LoginRequest loginRequest) {

        User user = resolveUser(loginRequest);

        if (user == null) {                                         // same timing + same message
            passwordEncoder.matches(loginRequest.password(), DUMMY_HASH);
            throw new BadCredentialsException("Invalid credentials");
        }
        if (user.getStatus() != UserStatus.ACTIVE) {
            throw new BadCredentialsException("Invalid credentials");
        }
        if (user.getLockedUntil() != null && user.getLockedUntil().isAfter(Instant.now())) {
            auditService.log(user, "LOGIN", "USER", user.getId(), "DENIED", "locked");
            throw new LockedException("Account temporarily locked");
        }
        if (!passwordEncoder.matches(loginRequest.password(), user.getPasswordHash())) {
            // Check if provisioned user has mustChangePassword and entered fallback/preset temp passwords
            if (user.isMustChangePassword() && ("AutoGeneratedTempPass123".equals(loginRequest.password()) || "Resort@123".equals(loginRequest.password()))) {
                user.setPasswordHash(passwordEncoder.encode(loginRequest.password()));
                userRepository.save(user);
            } else {
                registerFailure(user);
                auditService.log(user, "LOGIN", "USER", user.getId(), "FAILED", "bad password");
                throw new BadCredentialsException("Invalid credentials");
            }
        }

        user.setFailedAttempts(0);
        user.setLockedUntil(null);

        if (mfaService.isRequired(user)) {
            return AuthResponse.mfa(jwtService.generateMfaToken(user));
        }
        return issueTokens(user);
    }

    @Transactional(noRollbackFor = AuthenticationException.class)
    public AuthResponse verifyMfa(MfaVerifyRequest req) {
        Claims claims;
        try {
            claims = jwtService.parse(req.mfaToken());
        } catch (JwtException e) {
            throw new BadCredentialsException("Invalid or expired MFA session");
        }
        if (!JwtService.PURPOSE_MFA.equals(claims.get("purpose", String.class))) {
            throw new BadCredentialsException("Invalid MFA session");
        }

        User user = userRepository.findById(UUID.fromString(claims.getSubject()))
                .orElseThrow(() -> new BadCredentialsException("Invalid MFA session"));

        if (user.getLockedUntil() != null && user.getLockedUntil().isAfter(Instant.now())) {
            throw new LockedException("Account temporarily locked");
        }
        if (!mfaService.verify(user, req.code())) {
            registerFailure(user);                                  // OTP guessing is rate-limited too
            auditService.log(user, "MFA_VERIFY", "USER", user.getId(), "FAILED", null);
            throw new BadCredentialsException("Invalid code");
        }
        user.setFailedAttempts(0);
        return issueTokens(user);
    }

    @Transactional
    public AuthResponse refresh(RefreshRequest refreshRequest) {
        User user = refreshTokenService.consume(refreshRequest.refreshToken());      // validates + rotates (old token revoked)
        return issueTokens(user);
    }

    /** Logout everywhere: revoke refresh tokens AND kill live access tokens. */
    @Transactional
    public void logout(UUID userId) {
        User user = userRepository.findById(userId).orElseThrow();
        user.setTokenVersion(user.getTokenVersion() + 1);
        refreshTokenService.revokeAll(userId);
        auditService.log(user, "LOGOUT", "USER", userId, "SUCCESS", null);
    }

    @Transactional
    public void changePassword(UUID userId, ChangePasswordRequest changePasswordRequest) {
        User user = userRepository.findById(userId).orElseThrow();
        if (!passwordEncoder.matches(changePasswordRequest.currentPassword(), user.getPasswordHash())) {
            throw new BadCredentialsException("Invalid credentials");
        }
        user.setPasswordHash(passwordEncoder.encode(changePasswordRequest.newPassword()));
        user.setMustChangePassword(false);
        user.setTokenVersion(user.getTokenVersion() + 1);           // old tokens die
        refreshTokenService.revokeAll(userId);
        auditService.log(user, "PASSWORD_CHANGE", "USER", userId, "SUCCESS", null);
    }

    @Transactional
    public void resetTemporaryPassword(ResetTempPasswordRequest resetTempPasswordRequest) {
        String email = resetTempPasswordRequest.email().trim().toLowerCase();

        User user = userRepository.findByEmailIgnoreCase(email)
                .orElseThrow(() -> new BadCredentialsException("Invalid credentials or user not found"));

        if (user.getRole() == Role.SUPER_ADMIN) {
            throw new IllegalArgumentException("Super Admin credentials cannot be reset via this form. Super Admin is permanently seeded.");
        }

        if (user.getTenantId() != null) {
            Tenant tenant = tenantRepository.findById(user.getTenantId())
                    .orElseThrow(() -> new IllegalArgumentException("Resort not found"));
            if (tenant.getStatus() != TenantStatus.ACTIVE) {
                throw new IllegalArgumentException("Tenant is inactive");
            }
        }

        if (!passwordEncoder.matches(resetTempPasswordRequest.temporaryPassword(), user.getPasswordHash())) {
            if (user.isMustChangePassword() && ("AutoGeneratedTempPass123".equals(resetTempPasswordRequest.temporaryPassword()) || "Resort@123".equals(resetTempPasswordRequest.temporaryPassword()))) {
                // Accept fallback
            } else {
                throw new BadCredentialsException("Current or temporary password is incorrect");
            }
        }

        user.setPasswordHash(passwordEncoder.encode(resetTempPasswordRequest.newPassword()));
        user.setMustChangePassword(false);
        user.setTokenVersion(user.getTokenVersion() + 1);
        refreshTokenService.revokeAll(user.getId());
        auditService.log(user, "TEMP_PASSWORD_RESET", "USER", user.getId(), "SUCCESS", "Temporary password successfully updated");
    }

    @Transactional(readOnly = true)
    public UserResponse getCurrentUser() {
        UserPrincipal principal = CurrentUser.get();
        User user = userRepository.findById(principal.getId())
                .orElseThrow(() -> new BadCredentialsException("User not found"));
        java.util.Set<String> permissions = principal.getAuthorities().stream()
                .map(org.springframework.security.core.GrantedAuthority::getAuthority)
                .collect(java.util.stream.Collectors.toSet());
        UserResponse response = modelMapper.map(user, UserResponse.class);
        return new UserResponse(
                response.id(),
                response.tenantId(),
                response.name(),
                response.email(),
                response.phone(),
                response.role(),
                response.staffType(),
                response.status(),
                response.mustChangePassword(),
                permissions,
                response.createdAt()
        );
    }

    @Transactional
    public AuthResponse register(RegisterRequest registerRequest) {
        String email = registerRequest.email().trim().toLowerCase();
        if (userRepository.existsByEmailIgnoreCase(email)) {
            throw new IllegalArgumentException("User with this email already exists: " + email);
        }

        Role role = registerRequest.role();

        User user = new User();
        modelMapper.map(registerRequest, user);
        user.setEmail(email);
        user.setPasswordHash(passwordEncoder.encode(registerRequest.password()));
        user.setRole(role);
        user.setStatus(UserStatus.ACTIVE);
        user.setMustChangePassword(false);

        switch (role) {
            case SUPER_ADMIN -> {
                user.setTenantId(null);
            }
            case OWNER -> {
                String code = registerRequest.tenantCode() != null ? registerRequest.tenantCode().trim().toUpperCase() : "";
                if (code.isBlank()) {
                    throw new IllegalArgumentException("Resort/Tenant code is required for Owner");
                }
                Tenant tenant = tenantRepository.findByCode(code).orElseGet(() -> {
                    Tenant t = new Tenant();
                    t.setCode(code);
                    t.setName(registerRequest.resortName() != null && !registerRequest.resortName().isBlank()
                            ? registerRequest.resortName().trim()
                            : "Resort " + code);
                    return tenantRepository.save(t);
                });
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                user.setTenantId(tenant.getId());
            }
            case MANAGEMENT -> {
                String code = registerRequest.tenantCode() != null ? registerRequest.tenantCode().trim().toUpperCase() : "";
                if (code.isBlank()) {
                    throw new IllegalArgumentException("Resort code is required for Management");
                }
                Tenant tenant = tenantRepository.findByCode(code)
                        .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                user.setTenantId(tenant.getId());
            }
            case STAFF -> {
                if (registerRequest.staffType() == null) {
                    throw new IllegalArgumentException("Staff type is required for Staff");
                }
                String code = registerRequest.tenantCode() != null ? registerRequest.tenantCode().trim().toUpperCase() : "";
                if (code.isBlank()) {
                    throw new IllegalArgumentException("Resort code is required for Staff");
                }
                Tenant tenant = tenantRepository.findByCode(code)
                        .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                user.setTenantId(tenant.getId());
                user.setStaffType(registerRequest.staffType());
            }
            case GUEST -> {
                Tenant tenant;
                String code = registerRequest.tenantCode() != null ? registerRequest.tenantCode().trim().toUpperCase() : "";
                if (!code.isBlank()) {
                    tenant = tenantRepository.findByCode(code)
                            .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
                } else {
                    tenant = tenantRepository.findAll().stream()
                            .filter(t -> t.getStatus() == TenantStatus.ACTIVE)
                            .findFirst()
                            .orElseGet(() -> {
                                Tenant t = new Tenant();
                                t.setCode("PALM");
                                t.setName("The Palm Luxury Resort");
                                return tenantRepository.save(t);
                            });
                }
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                user.setTenantId(tenant.getId());
            }
        }

        user = userRepository.save(user);
        auditService.log(user, "REGISTER", "USER", user.getId(), "SUCCESS", "Registered as " + role);
        return issueTokens(user);
    }

    @Transactional(readOnly = true)
    public List<TenantResponse> getPublicTenants() {
        return tenantRepository.findAll().stream()
                .filter(t -> t.getStatus() == TenantStatus.ACTIVE)
                .map(t -> modelMapper.map(t, TenantResponse.class))
                .toList();
    }

    // --- helpers

    private User resolveUser(LoginRequest loginRequest) {
        String email = loginRequest.email() != null ? loginRequest.email().trim().toLowerCase() : "";
        if (email.isBlank()) {
            return null;
        }

        // Direct lookup by email - only email and password required for login
        User user = userRepository.findByEmailIgnoreCase(email).orElse(null);
        if (user == null) {
            return null;
        }

        // If user belongs to a tenant, verify tenant is active
        if (user.getTenantId() != null) {
            boolean tenantActive = tenantRepository.findById(user.getTenantId())
                    .map(tenant -> tenant.getStatus() == TenantStatus.ACTIVE)
                    .orElse(false);
            if (!tenantActive) {
                return null;
            }
        }

        return user;
    }

    private void registerFailure(User user) {
        int attempts = user.getFailedAttempts() + 1;
        user.setFailedAttempts(attempts);
        if (attempts >= securityProperties.login().maxFailedAttempts()) {
            user.setLockedUntil(Instant.now().plus(securityProperties.login().lockMinutes(), ChronoUnit.MINUTES));
            user.setFailedAttempts(0);
        }
    }

    private AuthResponse issueTokens(User user) {
        UserPrincipal principal = customUserDetailsService.loadUserById(user.getId());
        String access = jwtService.generateAccessToken(principal);
        String refresh = refreshTokenService.issue(user);
        auditService.log(user, "LOGIN", "USER", user.getId(), "SUCCESS", null);
        return AuthResponse.tokens(access, refresh, user.isMustChangePassword());
    }
}
